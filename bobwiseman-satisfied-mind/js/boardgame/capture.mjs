// Builds out/boardgame_tex/textures.js: the other looks' finished props as data-URL textures for the boardgame page
// (tarot cards + cloth from a copy of the tarot code, two engraved notes, the finished sampler).
// Run from the project dir: node js/boardgame/capture.mjs
import { chromium } from 'playwright';
import fs from 'fs';
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--ignore-gpu-blocklist', '--enable-gpu'] });
const tex = {};
const cropper = `window.__crop = (x, y, w, h, q = .92) => { const s = document.getElementById('c'); const c = document.createElement('canvas'); c.width = Math.round(w); c.height = Math.round(h); c.getContext('2d').drawImage(s, x, y, w, h, 0, 0, w, h); return c.toDataURL('image/jpeg', q); };`;
async function open(url, vw = 1920, vh = 1080) {
  const p = await b.newPage({ viewport: { width: vw, height: vh } });
  p.on('pageerror', (e) => console.log('pageerror', String(e)));
  await p.goto('file://' + process.cwd() + '/' + url + '?offline=1'); await p.evaluate(() => window.__ready); await p.evaluate(cropper); return p;
}
// tarot
{
  const p = await open('js/boardgame/tarot/capture.html', 2400, 2400);
  const T = 272.95;
  tex.mat = await p.evaluate((T) => { window.CAMOVR = { x: 0, y: 0, z: 2400 / 2600, r: 0 }; window.__frameJPEG(T); return window.__crop(0, 0, 2400, 2400, .9); }, T);
  const names = ['wheel', 'hourglass', 'company', 'fool', 'star'];
  for (let i = 0; i < 5; i++) {
    tex[names[i]] = await p.evaluate(([T, i]) => { const R = REST[i]; window.CAMOVR = { x: R[0], y: R[1], z: 3.5, r: R[2] }; window.__frameJPEG(T); const hw = 350 * CS * 3.5, hh = 600 * CS * 3.5; return window.__crop(1200 - hw, 1200 - hh, 2 * hw, 2 * hh); }, [T, i]);
  }
  tex.back = await p.evaluate((T) => { window.CAMOVR = { x: DECK[0] - 6 * 1.6, y: DECK[1] - 6 * 2.2, z: 3.5, r: DECK[2] }; window.__frameJPEG(T); const hw = 350 * CS * 3.5, hh = 600 * CS * 3.5; return window.__crop(1200 - hw, 1200 - hh, 2 * hw, 2 * hh); }, T);
  // where the spread sits on the mat (tarot units, mat centre = 0,0, 2600 units square)
  tex.spread = await p.evaluate(() => JSON.stringify({ REST, DECK, CS }));
  await p.close();
}
// banknotes
{
  const p = await open('looks/banknote.html');
  tex.note1 = await p.evaluate(() => { window.__frameJPEG(114.5); return window.__crop(551, 319, 998, 442); });
  tex.note2 = await p.evaluate(() => { window.__frameJPEG(85.2); return window.__crop(452, 315, 1016, 450); });
  await p.close();
}
// finished sampler
{
  const p = await open('looks/crossstitch.html');
  const r = await p.evaluate(() => {
    window.__frameJPEG(197.9);
    const s = document.getElementById('c'), g = s.getContext('2d'); const d = g.getImageData(0, 0, 1920, 1080).data;
    const br = (x, y) => { const k = (y * 1920 + x) * 4; return (d[k] + d[k + 1] + d[k + 2]) / 3; };
    let x0 = 0, x1 = 1919, y0 = 0, y1 = 1079;
    while (br(x0, 540) < 170) x0++; while (br(x1, 540) < 170) x1--; while (br(960, y0) < 170) y0++; while (br(960, y1) < 170) y1--;
    return { box: [x0, y0, x1, y1], url: window.__crop(x0 + 2, y0 + 2, x1 - x0 - 4, y1 - y0 - 4) };
  });
  console.log('sampler box', r.box); tex.sampler = r.url;
  await p.close();
}
await b.close();
fs.mkdirSync('out/boardgame_tex', { recursive: true });
fs.writeFileSync('out/boardgame_tex/textures.js', '// generated by js/boardgame/capture.mjs, do not commit\nwindow.EXT_TEX = ' + JSON.stringify(tex) + ';\n');
console.log('wrote out/boardgame_tex/textures.js', Object.keys(tex).join(' '));
