// Builds js/tv/gen/r3a-lines.js (gitignored: it quotes the lyric) from source/lines.json for round 3's TV-news
// span tv-A: stanzas 0-5, 0-95.916667 s (f0-f2302). Run from the project folder:
//   node js/tv/r3a-make-lines.mjs
import fs from 'fs';
const A = 0, B = 2302 / 24;
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
const keep = d.lines.filter(l => l.s >= A && Math.floor(l.s * 24 + 1e-6) < Math.round(B * 24))
  .map(l => ({ i: l.i, text: l.text, s: l.s, e: l.e, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.writeFileSync('js/tv/gen/r3a-lines.js', '// generated by js/tv/r3a-make-lines.mjs from source/lines.json. Do not edit.\nconst r3aTvLINES = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.length, 'lines', keep[0].i, '-', keep[keep.length - 1].i);
