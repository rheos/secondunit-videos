// Builds js/tv/gen/lines.js (gitignored: it quotes the lyric) from source/lines.json, the timed contract.
// Run from the project folder: node js/tv/make_lines.mjs
import fs from 'fs';
const T0 = 95.916667, T1 = 123.125;
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
const keep = d.lines.filter(l => l.s < T1 && l.e > T0 && l.s >= T0 - 0.05).map(l => ({ i: l.i, text: l.text, s: l.s, e: l.e, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.writeFileSync('js/tv/gen/lines.js', '// generated by js/tv/make_lines.mjs from source/lines.json. Do not edit.\nconst TV_LINES = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.map(l => `${l.i} ${l.s} ${l.text}`).join('\n'));
