// Round 3, agent tv-C: builds gen/r3c_lines.js (gitignored: it quotes the lyric) from source/lines.json for
// stanzas 12-14 (261.5-340.4583, f6276-f8171), plus lines 108-110, which are still on the teleprinter paper
// when the span opens (the strip carries on from stanza 11). Run from the project folder:
//   node js/tv/r3c-make-lines.mjs
import fs from 'fs';
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
const keep = d.lines.filter(l => l.i >= 108 && l.i <= 131)
  .map(l => ({ i: l.i, text: l.text, s: l.s, e: l.e, approx: !!l.approx, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.writeFileSync('gen/r3c_lines.js', '// generated by js/tv/r3c-make-lines.mjs from source/lines.json. Do not edit.\nconst R3C_LINES = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.map(l => `${l.i} ${l.s}${l.approx ? ' approx' : ''}`).join('\n'));
