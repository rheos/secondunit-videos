// Builds js/tv/gen/lines_r2.js (gitignored: it quotes the lyric) from source/lines.json for round 2's spans:
// stanza 7 (123.125-165.083333) and stanza 11 (240.916667-261.5). Run from the project folder:
//   node js/tv/make_lines_r2.mjs
import fs from 'fs';
const SPANS = [[123.125, 165.083333], [240.916667, 261.5]];
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
// a line belongs to a span when its first word starts inside it (a word sung on the span's last frame and
// carried by the next look is left to that look)
const keep = d.lines.filter(l => SPANS.some(([a, b]) => l.s >= a - 0.05 && Math.floor(l.s * 24 + 1e-6) < Math.round(b * 24) - 1))
  .map(l => ({ i: l.i, text: l.text, s: l.s, e: l.e, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.writeFileSync('js/tv/gen/lines_r2.js', '// generated by js/tv/make_lines_r2.mjs from source/lines.json. Do not edit.\nconst TV_LINES_R2 = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.map(l => `${l.i} ${l.s}`).join('\n'));
