// Builds gen/r3b_tv_lines.js (gitignored: it quotes the lyric) from source/lines.json for agent tv-B's span,
// stanzas 6-10 (song frames 2302-5782). Run from the project folder:  node js/tv/r3b-make-lines.mjs
import fs from 'fs';
const A = 2302 / 24, B = 5782 / 24;
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
// a line belongs to the span when its first word starts inside it
const keep = d.lines.filter(l => l.s >= A - 0.05 && Math.floor(l.s * 24 + 1e-6) < Math.round(B * 24) - 1)
  .map(l => ({ i: l.i, s: l.s, e: l.e, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/r3b_tv_lines.js', '// generated by js/tv/r3b-make-lines.mjs from source/lines.json. Do not edit.\nconst R3BTV_LINES = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.length, 'lines', keep[0].i, '-', keep[keep.length - 1].i);
