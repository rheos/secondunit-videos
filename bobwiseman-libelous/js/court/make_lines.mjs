// Builds js/court/gen/lines.js (gitignored: it quotes the lyric) from source/lines.json, the timed contract.
// node js/court/make_lines.mjs
import fs from 'fs';
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
const keep = d.lines.filter(l => l.i >= 108 && l.i <= 125).map(l => ({ i: l.i, s: l.s, e: l.e, approx: !!l.approx, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.mkdirSync('js/court/gen', { recursive: true });
fs.writeFileSync('js/court/gen/lines.js', '// generated by js/court/make_lines.mjs from source/lines.json. Do not edit.\nconst LINES = ' + JSON.stringify(keep, null, 0).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log('wrote', keep.length, 'lines');
