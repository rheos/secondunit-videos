// node js/leaflet/r3c-make_lines.mjs
// Round 3, leaf-C: copies lines 99-131 (the last two stanza-10 lines, carried at the top of the first page,
// then stanzas 11-13) out of source/lines.json into gen/r3c_leaf_lines.js as R3C_LEAF_LINES, so the page can load them
// over file:// without fetch. gen/ is gitignored, like source/: the words never go into git.
import fs from 'fs';
const all = JSON.parse(fs.readFileSync('source/lines.json', 'utf8')).lines;
const L = all.filter(l => l.i >= 99 && l.i <= 131);
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/r3c_leaf_lines.js', '// generated by js/leaflet/r3c-make_lines.mjs from source/lines.json; do not edit\nconst R3C_LEAF_LINES = ' + JSON.stringify(L) + ';\n');
console.log('wrote gen/r3c_leaf_lines.js', L.length, 'lines');
