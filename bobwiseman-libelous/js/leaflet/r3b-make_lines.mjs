// node js/leaflet/r3b-make_lines.mjs   (round 3, agent leaf-B)
// Copies lines 39-64 out of source/lines.json into gen/r3b_leaf_lines.js as R3BLEAF_LINES, so the page can load them over
// file:// with no fetch: 41-64 are stanzas 6 and 7; 39-40 (the end of stanza 5) are carried, already typed, at the
// top of the stanza-6 column so they stay readable across the cut. gen/ is gitignored, like source/.
import fs from 'fs';
const all = JSON.parse(fs.readFileSync('source/lines.json', 'utf8')).lines;
const L = all.filter(l => l.i >= 39 && l.i <= 64);
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/r3b_leaf_lines.js', '// generated by js/leaflet/r3b-make_lines.mjs from source/lines.json; do not edit\nconst R3BLEAF_LINES = ' + JSON.stringify(L) + ';\n');
console.log('wrote gen/r3b_leaf_lines.js', L.length, 'lines');
