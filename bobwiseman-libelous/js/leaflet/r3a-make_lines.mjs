// node js/leaflet/r3a-make_lines.mjs
// Round 3, leaf-A: copies lines 0-40 (stanzas 1-5) out of source/lines.json into gen/r3a_lines.js as R3A_LINES,
// so the page can load them over file:// (no fetch). gen/ is gitignored, like source/: the words never go into git.
import fs from 'fs';
const all = JSON.parse(fs.readFileSync('source/lines.json', 'utf8')).lines;
const L = all.filter(l => l.i >= 0 && l.i <= 40);
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/r3a_lines.js', '// generated by js/leaflet/r3a-make_lines.mjs from source/lines.json; do not edit\nconst R3A_LINES = ' + JSON.stringify(L) + ';\n');
console.log('wrote gen/r3a_lines.js', L.length, 'lines');
