// node js/leaflet/make_lines.mjs
// Copies the leaflet window's lines (87-100) out of source/lines.json into gen/leaflet_lines.js so the page can load
// them over file:// (no fetch). gen/ is gitignored, like source/: the words never go into git.
import fs from 'fs';
const L = JSON.parse(fs.readFileSync('source/lines.json', 'utf8')).lines.filter(l => l.i >= 87 && l.i <= 100);
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/leaflet_lines.js', '// generated by js/leaflet/make_lines.mjs from source/lines.json; do not edit\nconst LINES = ' + JSON.stringify(L) + ';\n');
console.log('wrote gen/leaflet_lines.js', L.length, 'lines');
