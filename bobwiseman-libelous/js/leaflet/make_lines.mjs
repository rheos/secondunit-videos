// node js/leaflet/make_lines.mjs
// Copies the leaflet's lines out of source/lines.json so the page can load them over file:// (no fetch):
//   gen/leaflet_lines.js        lines 87-100 (stanza 10, the couple) as LINES
//   gen/leaflet_lines_early.js  lines 65-86 (stanzas 8 and 9, the workers and the farms) as LINES_E
// gen/ is gitignored, like source/: the words never go into git.
import fs from 'fs';
const all = JSON.parse(fs.readFileSync('source/lines.json', 'utf8')).lines;
const L = all.filter(l => l.i >= 87 && l.i <= 100), E = all.filter(l => l.i >= 65 && l.i <= 86);
fs.mkdirSync('gen', { recursive: true });
fs.writeFileSync('gen/leaflet_lines.js', '// generated by js/leaflet/make_lines.mjs from source/lines.json; do not edit\nconst LINES = ' + JSON.stringify(L) + ';\n');
fs.writeFileSync('gen/leaflet_lines_early.js', '// generated by js/leaflet/make_lines.mjs from source/lines.json; do not edit\nconst LINES_E = ' + JSON.stringify(E) + ';\n');
console.log('wrote gen/leaflet_lines.js', L.length, 'lines; gen/leaflet_lines_early.js', E.length, 'lines');
