// Builds js/school/gen/lines.js (gitignored: it quotes the lyric) from source/lines.json, the timed contract.
// Run from the project folder: node js/school/make_lines.mjs
import fs from 'fs';
const T0 = 123.125, T1 = 165.083333;
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
// every line whose first word lands on a frame inside the window (onset frame = round(s * 24); the window is f2955-f3961)
const keep = d.lines.filter(l => Math.round(l.words[0].s * 24) >= 2955 && Math.round(l.words[0].s * 24) < 3962).map(l => ({ i: l.i, text: l.text, s: l.s, e: l.e, approx: !!l.approx, words: l.words.map(w => ({ w: w.w, s: w.s, e: w.e })) }));
fs.mkdirSync('js/school/gen', { recursive: true });
fs.writeFileSync('js/school/gen/lines.js', '// generated by js/school/make_lines.mjs from source/lines.json. Do not edit.\nconst SC_LINES = ' + JSON.stringify(keep).replace(/\},\{"i"/g, '},\n{"i"') + ';\n');
console.log(keep.map(l => `${l.i} ${l.s} ${l.text}`).join('\n'));
