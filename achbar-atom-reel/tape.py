# The tapes plate: cut the sentence out of the Atoms for Peace recording, write assets/ike.wav (48 kHz) and
# js/tape-data.js (TAPE_T0, TAPE_ENV at 24 fps, TAPE_WORDS from faster-whisper word times, shifted to film time).
#   viralvision venv python -I tape.py <atoms.mp3> <start s> <end s> <film t0>
import sys, os, json, subprocess, numpy as np, soundfile as sf
src, a, b, t0 = sys.argv[1], float(sys.argv[2]), float(sys.argv[3]), float(sys.argv[4])
here = os.path.dirname(os.path.abspath(__file__)); out = os.path.join(here, 'assets', 'ike.wav')
subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-ss', str(a), '-to', str(b), '-i', src, '-ar', '48000', '-ac', '1',
                '-af', f'afade=t=in:d=0.25,afade=t=out:st={b - a - 0.4}:d=0.4,highpass=f=80,alimiter=limit=0.8:level=false', out], check=True)
y, sr = sf.read(out); n = int(np.ceil(len(y) / sr * 24)); env = []
for i in range(n):
    seg = y[int(i * sr / 24):int((i + 1) * sr / 24)]; env.append(float(np.sqrt(np.mean(seg ** 2))) if len(seg) else 0.0)
env = np.array(env); env = env / max(env.max(), 1e-6); env = np.convolve(env, [.25, .5, .25], 'same')
from faster_whisper import WhisperModel
m = WhisperModel('small', compute_type='int8'); segs, _ = m.transcribe(out, word_timestamps=True, language='en')
words = [[round(t0 + w.start, 3), w.word.strip()] for s in segs for w in s.words if w.word.strip()]
js = "// Generated by tape.py from the Eisenhower Library recording of the Atoms for Peace speech (8 Dec 1953), the clip\n"
js += f"// {a:.2f}-{b:.2f} s of atoms.mp3. TAPE_T0 is film time; TAPE_ENV is the voice's envelope at 24 fps; TAPE_WORDS are whisper word times (timing only).\n'use strict';\n"
js += f"const TAPE_T0 = {t0};\nconst TAPE_ENV = {json.dumps([round(float(v), 3) for v in env])};\nconst TAPE_WORDS = {json.dumps(words)};\n"
open(os.path.join(here, 'js', 'tape-data.js'), 'w').write(js)
print('clip', round(b - a, 2), 's; words:', ' '.join(w for _, w in words))
