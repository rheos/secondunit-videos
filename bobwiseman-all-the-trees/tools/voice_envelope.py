"""Per-frame voice level (24 fps) from the Demucs vocal stem, for the opening's mouths (the radio DJ, then
the French singer). Writes js/alchemy/voice.js: numbers only, no words. Usage: voice_envelope.py <vocals.wav> <t1>"""
import sys, json, numpy as np, soundfile as sf
y, sr = sf.read(sys.argv[1]); y = y.mean(1) if y.ndim > 1 else y
t1 = float(sys.argv[2]); n = int(t1 * 24); hop = sr / 24
rms = np.array([np.sqrt(np.mean(y[int(i * hop):int((i + 1) * hop)] ** 2) + 1e-12) for i in range(n)])
db = 20 * np.log10(rms); ref = np.percentile(db[db > -70], 95) if (db > -70).any() else db.max()
env = np.clip((db - (ref - 30)) / 30, 0, 1)
open('js/alchemy/voice.js', 'w').write('// Generated by tools/voice_envelope.py: vocal-stem level per 24 fps frame, 0-1, for the opening mouths.\n'
    'window.ALCHEMY_VOICE=' + json.dumps({'fps': 24, 'env': [round(float(v), 2) for v in env]}, separators=(',', ':')) + ';\n')
print(n, 'frames; open-mouth frames >.55:', int((env > .55).sum()))
