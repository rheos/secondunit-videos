"""Per-frame mouth envelope (24 fps) from the Demucs vocal stem, for the opening's mouths (the radio DJ, then the
French singer). Writes js/alchemy/voice.js: numbers only, no words.

v18 (Robin, 2026-10-15): the DJ's mouth hung open through the breath after her drawn-out "uhh" at 0:07. Loudness
alone can't see that breath (it is breathy noise, as loud as speech), so the mouth now follows VOICING: a frame is
open only when the voice is pitched, and it also closes on a sharp dip (the voice falling well below its level just
before), so a held vowel ends with the mouth shutting before the next word.
Usage: voice_envelope.py <vocals.wav> <t1>"""
import sys, json, numpy as np, librosa
wav, t1 = sys.argv[1], float(sys.argv[2])
sr, hop = 22050, 220
y, _ = librosa.load(wav, sr=sr, mono=True, duration=t1 + .5)
rms = librosa.feature.rms(y=y, frame_length=882, hop_length=hop)[0]; db = 20 * np.log10(rms + 1e-9)
f0, voiced, prob = librosa.pyin(y, fmin=90, fmax=600, sr=sr, frame_length=1024, hop_length=hop)
tt = np.arange(len(db)) * hop / sr
n = int(t1 * 24); env = np.zeros(n)
ref = np.percentile(db[db > -60], 95)
for i in range(n):
    m = (tt >= i / 24) & (tt < (i + 1) / 24)
    if not m.any(): continue
    v = voiced[m].mean()
    lvl = np.clip((db[m].max() - (ref - 30)) / 30, 0, 1)
    # the level just before: a drop of 5 dB or more against the last 0.3 s means the vowel has ended
    back = (tt >= i / 24 - .3) & (tt < i / 24)
    dip = back.any() and db[m].mean() < db[back].max() - 5
    env[i] = 0 if (v < .5 or dip) else lvl
# a one-frame close is a flicker, not a breath: hold it shut for a second frame so it reads
op = env > .6
for i in range(1, n - 1):
    if op[i - 1] and not op[i] and op[i + 1]: env[i + 1] = 0; op[i + 1] = False
open('js/alchemy/voice.js', 'w').write('// Generated by tools/voice_envelope.py: voiced vocal level per 24 fps frame, 0-1, for the opening mouths.\n'
    'window.ALCHEMY_VOICE=' + json.dumps({'fps': 24, 'env': [round(float(v), 2) for v in env]}, separators=(',', ':')) + ';\n')
print(n, 'frames; open frames >.6:', int((env > .6).sum()))
