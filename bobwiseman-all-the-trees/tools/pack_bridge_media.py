"""Pack the love bridge's cut-outs (source/alchemy/bridge/<name>.png: a balloon statesman, a balloon diva and a
cherub with a snowball cannon; invented figures, GPT Image via Codex, draft 4) into assets/alchemy/bridge-media.js as data URIs, so the page renders from
file:// without a tainted canvas. Faint halo (alpha < 40) cleared, cropped to the figure, scaled to 900 px on the
long side."""
import base64, io, json
from pathlib import Path
import numpy as np
from PIL import Image
src = Path('source/alchemy/bridge'); out = Path('assets/alchemy/bridge-media.js')
media, boxes = {}, {}
for name in ['statesman', 'diva', 'cherub']:
    a = np.asarray(Image.open(src / f'{name}.png').convert('RGBA')).copy()
    al = a[..., 3].astype(float); al[al < 40] = 0; al[al > 235] = 255; a[..., 3] = al.astype(np.uint8)
    ys, xs = np.where(a[..., 3] > 0); x0, y0, x1, y1 = xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5
    im = Image.fromarray(a).crop((x0, y0, x1, y1)); s = 900 / max(im.size)
    im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True)
    media[name] = 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()
    boxes[name] = [im.width, im.height]; print(name, boxes[name], len(b.getvalue()) // 1024, 'KB')
out.write_text('// Generated by tools/pack_bridge_media.py (local media, not committed).\n'
               f'window.ALCHEMY_BRIDGE_MEDIA={json.dumps(media)};\nwindow.ALCHEMY_BRIDGE_BOX={json.dumps(boxes)};\n')
print('wrote', out)
