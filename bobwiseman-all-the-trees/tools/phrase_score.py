"""Trumpet score with phrases and breaths, from Robin's listening marks plus the audio.

Robin's held-key marks (TRUMPET-TAP.html) say where the trumpets play. Inside each marked passage the
breaths are found in the audio: short dips in the harmonic 700-4500 Hz level of the drum-free Demucs
'other' stem, measured against the local playing level. Passages split at the breaths into phrases;
attacks inside a phrase are notes (each re-strikes the bell). Writes the renderer's score and charts.

Usage: phrase_score.py <marks.json> <other.wav> <other-onsets.json> <score.js> <chart-prefix>
"""
import sys, json, numpy as np, librosa, scipy.ndimage as ndi
from PIL import Image, ImageDraw

marks_p, wav, ons_p, out_js, chart = sys.argv[1:6]
FPS, FRAMES, sr, hop = 24, 3674, 22050, 256
marks = [m for m in json.load(open(marks_p)) if m[1] - m[0] >= .25]
onsets = json.load(open(ons_p))['onsets']
y, _ = librosa.load(wav, sr=sr, mono=True)
Hm, _ = librosa.decompose.hpss(librosa.stft(y, n_fft=2048, hop_length=hop), margin=1.5)
S = np.abs(Hm); f = librosa.fft_frequencies(sr=sr, n_fft=2048)
lvl = 10 * np.log10((S[(f > 700) & (f < 4500)] ** 2).sum(0) + 1e-10)
fr = sr / hop; lvl = ndi.uniform_filter1d(lvl, max(1, int(.04 * fr))); t = np.arange(len(lvl)) / fr
local = ndi.percentile_filter(lvl, 80, size=int(1.5 * fr))
DIP, MIN_GAP, MAX_GAP, MIN_PHRASE = 8.0, .095, 1.2, .18
# Chorus 2 repeats chorus 1's arrangement 31.50 s later (chroma cross-correlation 0.68 vs 0.31 baseline),
# but its mix is too dense for the level to dip, so it borrows chorus 1's breaths.
REPEATS = [((79.3, 95.8), (47.9, 64.3), 31.50)]

def snap_start(s):
    c = [o for o in onsets if s - .35 <= o['t'] <= s + .15 and o['s'] >= .08]
    return min(c, key=lambda o: abs(o['t'] - s) - .3 * o['s'])['t'] if c else s

phrases, breaths = [], []
for s, e in marks:
    a = snap_start(s)
    i0, i1 = int(a * fr), int(e * fr)
    # The passage ends where the level falls away near the release, not at the release itself.
    floor = np.median(lvl[i0:i1]) - 12
    j = i1
    while j > i0 + int(.3 * fr) and j > i1 - int(.4 * fr) and lvl[j] < floor: j -= 1
    end = t[j]
    gap = (lvl[i0:j] < local[i0:j] - DIP)
    runs, k = [], 0
    while k < len(gap):
        if gap[k]:
            m = k
            while m < len(gap) and gap[m]: m += 1
            g0, g1 = t[i0 + k], t[i0 + m - 1]
            if MIN_GAP <= g1 - g0 <= MAX_GAP: runs.append([g0, g1])
            k = m
        else: k += 1
    for (ra, rb), (sa, sb), off in REPEATS:
        if ra <= a <= rb and len(runs) < 3:
            runs = [[g0 + off, g1 + off] for g0, g1 in breaths if sa <= g0 <= sb and a < g0 + off < end]
    cur = a
    for g0, g1 in runs:
        if g0 - cur >= MIN_PHRASE:
            phrases.append([cur, g0]); breaths.append([g0, g1]); cur = g1
    phrases.append([cur, end])

intervals, notes = [], []
for a, b in phrases:
    fa, fb = int(round(a * FPS)), min(FRAMES, int(round(b * FPS)))
    if fb <= fa: fb = fa + 1
    if intervals and fa <= intervals[-1][1]: fa = intervals[-1][1] + 1
    if fb <= fa: continue
    intervals.append([fa, fb]); notes.append(fa)
    notes += [int(round(o['t'] * FPS)) for o in onsets if fa + 3 <= round(o['t'] * FPS) < fb - 1 and o['s'] >= .1]
notes = sorted(set(notes))
score = {'verified': True, 'fps': FPS, 'intervals': intervals, 'notes': notes,
         'source': "Robin's listening marks (TRUMPET-TAP.html, 2026-10-14); phrases split at breaths found in the Demucs 'other' stem (tools/phrase_score.py)"}
open(out_js, 'w').write('// Generated by tools/phrase_score.py from Robin\'s listening marks plus the audio. Edit the marks, not this file.\n'
                        'window.ALCHEMY_TRUMPET_SCORE=' + json.dumps(score, separators=(',', ':')) + ';\n')
print(f'{len(marks)} passages -> {len(intervals)} phrases, {len(breaths)} breaths, {len(notes)} notes')
for a, b in breaths: print(f'  breath {a:7.2f}-{b:7.2f} ({(b-a)*1000:.0f} ms)')
# Charts over the other stem: phrases green, breaths blue, notes red, level trace yellow.
C = np.abs(librosa.cqt(y, sr=sr, hop_length=128, fmin=librosa.note_to_hz('E2'), n_bins=168, bins_per_octave=24))
D = librosa.amplitude_to_db(C, ref=np.max); cf = sr / 128; dur = len(y) / sr
for k, (ma, mb) in enumerate(marks):
    t0 = max(0, ma - .5)
    while t0 < mb:
        win = 12; a_, b_ = int(t0 * cf), int(min(t0 + win, dur) * cf)
        seg = np.clip((D[:, a_:b_] + 70) / 70, 0, 1)[::-1]
        im = Image.fromarray(np.uint8(190 * seg ** 1.3)).resize((1800, 504)); im = Image.merge('RGB', (im, im, im)); d = ImageDraw.Draw(im)
        X = lambda s: int((s - t0) / win * 1800)
        for s in np.arange(np.ceil(t0 * 2) / 2, t0 + win, .5):
            d.line((X(s), 0, X(s), 504), fill=(0, 90, 200) if s % 1 == 0 else (0, 45, 100))
            if s % 1 == 0: d.text((X(s) + 3, 3), f'{s:.0f}', fill=(255, 255, 0))
        for a, b in phrases: d.rectangle((X(a), 478, X(b), 498), fill=(40, 200, 80))
        for a, b in breaths: d.rectangle((X(a), 470, X(b), 504), fill=(60, 140, 255))
        for n in notes: d.line((X(n / FPS), 455, X(n / FPS), 476), fill=(255, 70, 50), width=2)
        i0, i1 = int(t0 * fr), int(min(t0 + win, dur) * fr)
        d.line([(X(t[i]), 440 - int(np.clip((lvl[i] - lvl.max() + 50) / 50, 0, 1) * 150)) for i in range(i0, min(i1, len(t)), 2)], fill=(255, 210, 60), width=2)
        im.save(f'{chart}_{k}_{t0:06.1f}.png'); t0 += win
