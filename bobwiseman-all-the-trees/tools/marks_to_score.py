"""Turn Robin's held-key trumpet marks (TRUMPET-TAP.html, seconds) into the renderer's trumpet score.

A held key starts late (reaction time) and ends late (release), so each start is snapped to the best
note attack in the 'other' stem shortly before the press, each end is pulled back by the release lag,
and every attack inside a held passage becomes a note (a fresh bell burst).

Usage: marks_to_score.py <marks.json> <other-onsets.json> [js/alchemy/trumpet-score.js]
"""
import json, sys
from pathlib import Path

FPS, FRAMES = 24, 3674
REACT, RELEASE = .22, .18  # typical press and release lag, seconds

marks = json.loads(Path(sys.argv[1]).read_text())
marks = marks.get('marks', marks) if isinstance(marks, dict) else marks
onsets = json.loads(Path(sys.argv[2]).read_text())['onsets']
out_path = Path(sys.argv[3] if len(sys.argv) > 3 else 'js/alchemy/trumpet-score.js')

def snap_start(s):
    cands = [o for o in onsets if s - .55 <= o['t'] <= s + .08]
    if not cands:
        return max(0., s - REACT), False
    best = max(cands, key=lambda o: o['s'] - .9 * abs(o['t'] - (s - REACT)))
    return best['t'], True

spans = []
for s, e in sorted(marks):
    on, snapped = snap_start(s)
    off = max(on + .15, e - RELEASE)
    spans.append([on, off, snapped])
merged = []
for on, off, sn in spans:
    if merged and on - merged[-1][1] < .12:
        merged[-1][1] = max(merged[-1][1], off)
    else:
        merged.append([on, off, sn])

intervals, notes = [], []
for on, off, _ in merged:
    a, b = int(round(on * FPS)), min(FRAMES, int(round(off * FPS)))
    if b <= a:
        b = a + 1
    intervals.append([a, b])
    notes.append(a)
    for o in onsets:
        f = int(round(o['t'] * FPS))
        if a + 3 <= f < b - 1 and o['s'] >= .1:
            notes.append(f)
notes = sorted(set(notes))
score = {'verified': True, 'fps': FPS, 'intervals': intervals, 'notes': notes,
         'source': "Robin's held-key marks while listening (TRUMPET-TAP.html), starts snapped to attacks in the Demucs 'other' stem"}
out_path.write_text('// Generated by tools/marks_to_score.py from a listening pass. Edit the marks, not this file.\n'
                    'window.ALCHEMY_TRUMPET_SCORE=' + json.dumps(score, separators=(',', ':')) + ';\n')
snapped = sum(1 for m in merged if m[2])
total = sum(b - a for a, b in intervals) / FPS
print(f'{len(marks)} marks -> {len(intervals)} passages ({snapped} snapped to an attack), {len(notes)} notes, {total:.1f} s of trumpet')
