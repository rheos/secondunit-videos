// bundle.mjs · node tools/bundle.mjs [src/entry.js build/out.js]   (default: src/film.js -> build/film.js)
// Joins an entry module and every module it imports (paper-fox's core in vendor/ included, unchanged) into one
// classic script, build/film.js, so the page opens from file:// the way our renderers and the cloud render load
// it. Each module becomes a function scope that returns its exports; imports become destructuring of those.
// Handles the forms this folder uses: `import { a, b as c } from './x.js'` and `export function|const|let|class`.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const order = [], seen = new Set();
const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm;

function visit(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(IMPORT)) visit(path.resolve(path.dirname(file), m[2]));
  order.push(file);
}
const [ENTRY = 'src/film.js', OUT = 'build/film.js'] = process.argv.slice(2);
visit(path.join(ROOT, ENTRY));

const id = (f) => path.relative(ROOT, f);
let out = `// GENERATED by tools/bundle.mjs from src/ and vendor/paper-fox/ (MIT, Copyright (c) 2026 Leonxlnx). Do not edit.\n(() => {\nconst __m = {};\n`;
for (const file of order) {
  let src = fs.readFileSync(file, 'utf8');
  const names = [];
  src = src.replace(IMPORT, (_, list, dep) => {
    const parts = list.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/\s+as\s+/, ': '));
    return `const { ${parts.join(', ')} } = __m[${JSON.stringify(id(path.resolve(path.dirname(file), dep)))}];`;
  });
  src = src.replace(/^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => { names.push(name); return `${kw} ${name}`; });
  if (/^export\s/m.test(src)) throw new Error(`unsupported export form in ${id(file)}`);
  out += `__m[${JSON.stringify(id(file))}] = (() => {\n${src}\nreturn { ${names.join(', ')} };\n})();\n`;
}
out += '})();\n';
fs.mkdirSync(path.dirname(path.join(ROOT, OUT)), { recursive: true });
fs.writeFileSync(path.join(ROOT, OUT), out);
console.log(`${OUT}: ${order.length} modules, ${(out.length / 1024).toFixed(0)} KB`);
