// LYRICS for Giulietta Masina (issue rheos/secondunit-videos#117): every sung word on screen on its onset, in each
// look's own material, never over a face. Loaded by the caption pages (looks/<look>-cap.html, looks/<look>-9x16-cap.html)
// AFTER the look's own scripts; the approved look files are not edited.
//
//   film   (kite, dream, leader): burned-in subtitles in the dream's style (js/dream/film.js drawSubs): white Helvetica
//          Neue with a dark edge and a faint glow, the whole line laid out at once, each word printing on its onset.
//          The chant stays in italics, a whisper, as the dream set it. In kite and dream the
//          subtitles are drawn inside the print (filmOut calls drawSubs, which this file replaces), so they weave with
//          the gate like the rest of the frame.
//   poster (verse 2): a paper snipe pasted on the poster, the line hand-brushed on it in the poster's own lettering
//          (js/poster/paint.js brushLettering), each word brushed on its onset.
//
// Words come from js/gen/lyrics.js (LYR, generated by tools/make_lyrics.mjs from source/lines.json; gitignored because
// it quotes the lyric). A line shows from 0.25 s before its first word until its hide time (line.b).
//
// WHERE: every drawn head reports a box (js/lyrics/faces-<look>.js wraps the look's head functions; FACES, in 16:9
// output px). tools/place_captions.mjs scans every captioned frame and writes js/lyrics/cap-place.js: per aspect, per
// line, per stretch of frames, which layout and where. A caption only moves on a shot cut or when a head would pass
// under it. Without a placement it sits bottom centre.
//
// 9:16 (window.CAP_TALL): the 16:9 frame is drawn as usual (no caption), a 607.5 x 1080 window is cut out of it
// (centre from the pan-and-scan plan, PANPLAN, aspects/9x16/panscan-plan-v1.js) and scaled to 720 x 1280, and the
// caption is drawn on the tall frame at its own resolution, laid out for the tall frame.
const CAP_F = 24;
const CAP_TALL = !!window.CAP_TALL;
const CAP_KIND = window.CAP_KIND || 'film';
const TW = 720, TH = 1280, CROPW = 1080 * 9 / 16;
const capFrame = (t) => Math.round(t * CAP_F);
const capOn = (t, s) => capFrame(t) >= Math.floor(s * CAP_F + 1e-6);
const CPROBE = (typeof ML !== 'undefined' && ML.probe) || { on: false, text() {}, box() {}, edge() {} };
const capPrev = (t) => (typeof ML !== 'undefined' ? ML.prevT(t) : t - 1 / CAP_F);
const capRec = (r) => { if (Array.isArray(window.__probeLog)) window.__probeLog.push(r); };

// ---------- faces ----------
// FACES: head boxes drawn this frame, [x0, y0, x1, y1] in 16:9 output px (1920 x 1080). capFace() takes a box in the
// local coordinates of context g (through its current transform) and maps the canvas it is drawn on to the output frame.
let FACES = [];
const CAP_MAPS = [];           // per page: (canvas, [x0,y0,x1,y1] canvas px) -> output box or null (not ours)
function capFace(g, x0, y0, x1, y1) {
  const m = g.getTransform(), P = [[x0, y0], [x1, y0], [x0, y1], [x1, y1]].map(([x, y]) => [m.a * x + m.c * y + m.e, m.b * x + m.d * y + m.f]);
  const b = [Math.min(...P.map((p) => p[0])), Math.min(...P.map((p) => p[1])), Math.max(...P.map((p) => p[0])), Math.max(...P.map((p) => p[1]))];
  for (const f of CAP_MAPS) { const r = f(g.canvas, b); if (r) { FACES.push(r); return; } }
}
function capFaceOut(b) { FACES.push(b); }
// wrap a global head-drawing function: box(args) gives the head box in the caller's coordinates
function capWrap(name, box) {
  const f = window[name]; if (typeof f !== 'function') throw new Error('capWrap: no function ' + name);
  window[name] = function (g, ...a) { const b = box(...a); if (b) capFace(g, ...b); return f.call(this, g, ...a); };
}
// the film print: the scene canvas SC (frame units x RS) printed into 1920 x 1080 (filmOut: 6 px overscan, gate weave
// up to ~3 px, 21 px bars). The box grows by 8 px to cover the weave.
if (typeof SC !== 'undefined' && typeof RS !== 'undefined') CAP_MAPS.push((c, b) => c === SC ? [b[0] / RS * (FW + 12) / FW - 6 - 8, b[1] / RS * (FH + 12) / FH - 6 + BAR - 8, b[2] / RS * (FW + 12) / FW - 6 + 8, b[3] / RS * (FH + 12) / FH - 6 + BAR + 8] : null);
CAP_MAPS.push((c, b) => c === out ? b : null);

// ---------- lines ----------
// CAP_GAPS[aspect]: song-frame spans [f0, f1) with no caption in that aspect (set by a faces-<look>.js where a shot is
// all face, e.g. the poster's crying close in 9:16). Words whose onset falls in a gap print on the gap's last frame + 1.
const CAP_GAPS = window.CAP_GAPS || {};
const capGap = (t) => (CAP_GAPS[CAP_TALL ? 'tall' : 'wide'] || []).some(([a, b]) => capFrame(t) >= a && capFrame(t) < b);
function capLine(t) {
  if (typeof LYR === 'undefined' || capGap(t)) return -1;
  for (let i = LYR.length - 1; i >= 0; i--) { const L = LYR[i]; if (t >= L.a && t < L.b) return i; }
  return -1;
}

// ---------- the styles ----------
// sizes in OUTPUT px of the aspect being drawn: wide 1920 x 1080, tall 720 x 1280. Layouts widest first; the placer
// tries narrower ones (more rows) to fit between heads.
const CAP_STYLE = {
  film: {
    wide: { area: [60, 70, 1860, 1040], pad: [14, 8], lead: 1.18, bottom: 1022, layouts: [{ size: 56, maxW: 1190 }, { size: 54, maxW: 820 }, { size: 52, maxW: 560 }] },
    tall: { area: [30, 150, 640, 1030], pad: [10, 6], lead: 1.18, bottom: 980, layouts: [{ size: 40, maxW: 590 }, { size: 38, maxW: 430 }, { size: 36, maxW: 330 }] },
  },
  poster: {
    wide: { area: [52, 52, 1868, 1040], pad: [30, 16], lead: 1.1, bottom: 1018, layouts: [{ size: 84, maxW: 1240 }, { size: 78, maxW: 860 }, { size: 72, maxW: 620 }, { size: 66, maxW: 300 }] },
    tall: { area: [30, 150, 640, 1030], pad: [18, 10], lead: 1.08, bottom: 980, layouts: [{ size: 54, maxW: 570 }, { size: 50, maxW: 440 }, { size: 46, maxW: 340 }] },
  },
};
const capKey = () => (CAP_TALL ? 'tall' : 'wide');
const CAPFONT = (sz, it) => `${it ? 'italic ' : ''}500 ${sz}px "Helvetica Neue", Helvetica, Arial, sans-serif`;
const CMC = document.createElement('canvas').getContext('2d');
// measured word widths at size sz for line li (film: the font; poster: the baked brush word's ink box)
function capWidths(li, sz) {
  const L = LYR[li];
  if (CAP_KIND === 'poster') return L.words.map((w, k) => { const B = BRUSH[li][k]; return (B.box[2] - B.box[0]) * sz / B.size; });
  CMC.font = CAPFONT(sz, L.it); return L.words.map((w) => CMC.measureText(w.w).width);
}
const capSpace = (sz) => (CAP_KIND === 'poster' ? sz * .34 : sz * .28);
// rows of words that fit maxW, balanced (the fewest rows, the most even split)
function capLayout(li, key, n) {
  const S = CAP_STYLE[CAP_KIND][key], Y = S.layouts[n], ww = capWidths(li, Y.size), sp = capSpace(Y.size), N = ww.length;
  const rowW = (a, b) => ww.slice(a, b).reduce((x, y) => x + y, 0) + sp * (b - a - 1);
  let best = null;
  for (let r = 1; r <= N && !best; r++) {
    const total = rowW(0, N);
    for (let tgt = Math.min(Y.maxW, total / r + Y.size * 2); tgt <= Y.maxW + 1; tgt += 8) {
      const rows = []; let a = 0;
      for (let i = 1; i <= N; i++) if (i === N || rowW(a, i + 1) > tgt) { rows.push([a, i]); a = i; }
      if (rows.length === r && rows.every(([x, y]) => rowW(x, y) <= Y.maxW)) { best = rows; break; }
    }
  }
  if (!best) best = ww.map((_, i) => [i, i + 1]);
  const rw = best.map(([a, b]) => rowW(a, b)), w = Math.max(...rw), lh = Y.size * S.lead, runs = [];
  best.forEach(([a, b], r) => { let x = -rw[r] / 2; for (let i = a; i < b; i++) { runs.push({ i, x, r, w: ww[i] }); x += ww[i] + sp; } });
  return { runs, size: Y.size, w: Math.ceil(w + S.pad[0] * 2), h: Math.ceil(lh * best.length + S.pad[1] * 2), lh, rows: best.length };
}
const CAP_LAY = {};
const capLay = (li, key, n) => CAP_LAY[`${key}${li}.${n}`] || (CAP_LAY[`${key}${li}.${n}`] = capLayout(li, key, n));
// where line li sits on song frame f: [layout, x0, y0, first frame of this stretch] (output px of the aspect)
function capWhere(li, key, f) {
  const tab = typeof CAP_PLACE !== 'undefined' && CAP_PLACE[CAP_KIND + '-' + key] && CAP_PLACE[CAP_KIND + '-' + key][li];
  if (tab) { for (const [f0, f1, n, x0, y0] of tab) if (f >= f0 && f < f1) return [n, x0, y0, f0]; }
  const S = CAP_STYLE[CAP_KIND][key], lay = capLay(li, key, 0), cx = (S.area[0] + S.area[2]) / 2;
  return [0, Math.round(cx - lay.w / 2), S.bottom - lay.h, null];
}

// ---------- poster: baked brush words and snipes ----------
let BRUSH = null;
const SNIPE = {};
function capBakePoster() {
  if (CAP_KIND !== 'poster' || typeof LYR === 'undefined') return;
  // only the lines that show on the poster (34-60 s): brushing all 83 words took ~3 min per page load
  BRUSH = LYR.map((L, li) => !(L.b > 33.9 && L.a < 60.1) ? null : L.words.map((w, k) => {
    const size = 150, B = brushLettering(w.w.toUpperCase(), { seed: 7000 + li * 37 + k * 5, size, col: hex('#a81a20'), col2: hex('#c43024'), shadow: hex('#1c2668'), lean: .12, shadowOff: [size * .035, size * .04] });
    // ink box measured by brushLettering (letters + shadow); the word image is drawn scaled so its ink box is sz tall-ish
    return { ...B, size };
  }));
}
// a cream paper snipe the size of the line (painted band, paper tooth), baked per line and layout
function capSnipe(li, key, n) {
  const id = `${key}${li}.${n}`; if (SNIPE[id]) return SNIPE[id];
  const lay = capLay(li, key, n), c = mkCanvas(lay.w * 2, lay.h * 2), sg2 = c.getContext('2d', { willReadFrequently: true }), R = mulberry(8100 + li * 13 + n);
  sg2.scale(2, 2); paintBand(sg2, 0, 0, lay.w, lay.h, hex('#f2e4c0'), R); paperize(sg2, c.width, c.height, .7);
  return (SNIPE[id] = c);
}

// ---------- drawing ----------
// g in OUTPUT px of the aspect (wide: identity on the look's canvas; tall: the tall canvas)
function capDraw(g, t, key) {
  const li = capLine(t); if (li < 0) return;
  const f = capFrame(t), where = capWhere(li, key, f); if (!where) return;
  const L = LYR[li], [n, x0, y0, f0] = where, lay = capLay(li, key, n), S = CAP_STYLE[CAP_KIND][key];
  const cx = x0 + lay.w / 2, area = S.area;
  CPROBE.box(g, 'lyric block', x0, y0, lay.w, lay.h, { keep: true });
  capRec({ kind: 'box', name: 'lyric block', box: [x0, y0, x0 + lay.w, y0 + lay.h], frame: [g.canvas.width, g.canvas.height] });
  if (CAP_KIND === 'poster') {
    // the snipe drops open from its top edge over 4 frames when the line first comes up, then holds; when it moves on a
    // cut it is simply there in the new framing (re-dropping hid the words for 3 frames)
    const fIn = f - Math.floor(L.a * CAP_F + 1e-6), u = clamp((fIn + 1) / 4);
    g.save();
    g.fillStyle = 'rgba(10,6,18,.3)'; g.fillRect(x0 + 4, y0 + 5, lay.w, lay.h * u);
    g.beginPath(); g.rect(x0, y0, lay.w, lay.h * u); g.clip();
    g.drawImage(capSnipe(li, key, n), x0, y0, lay.w, lay.h);
    g.restore();
    if (u < 1) return;
  }
  const base = y0 + S.pad[1] + lay.lh * .5 + lay.size * .36;
  g.save(); g.textAlign = 'left'; g.textBaseline = 'alphabetic'; g.lineJoin = 'round';
  for (const R of lay.runs) {
    const W_ = L.words[R.i], x = cx + R.x, y = base + R.r * lay.lh, on = capOn(t, W_.s);
    // fires on the first frame the word is DRAWN (a caption gap holds it back; the audit then reports it late)
    CPROBE.edge(`word#${li}.${R.i}`, on, capOn(capPrev(t), W_.s) && !capGap(capPrev(t)) && capLine(capPrev(t)) === li);
    if (!on) continue;
    if (CAP_KIND === 'poster') {
      // brushed on left to right over 3 frames
      const B = BRUSH[li][R.i], k = lay.size / B.size, u = clamp((f - Math.floor(W_.s * CAP_F + 1e-6) + 1) / 3);
      const ix = x - B.box[0] * k, iy = y - lay.size * .86 - B.box[1] * k + (lay.size - (B.box[3] - B.box[1]) * k) * .5;
      g.save(); g.beginPath(); g.rect(x - 4, y0, (R.w + 8) * u, lay.h); g.clip(); g.drawImage(B.c, ix, iy, B.w * k, B.h * k); g.restore();
      capRec({ kind: 'text', name: 'lyric', str: W_.w, box: [x, iy + B.box[1] * k, x + R.w, iy + B.box[3] * k], frame: [g.canvas.width, g.canvas.height], container: [x0, y0, x0 + lay.w, y0 + lay.h], margin: 10, keep: false });
    } else {
      g.font = CAPFONT(lay.size, L.it);
      g.lineWidth = lay.size * .14; g.strokeStyle = 'rgba(8,8,8,.85)'; g.strokeText(W_.w, x, y);
      g.shadowColor = 'rgba(255,255,255,.45)'; g.shadowBlur = 7 * lay.size / 56; g.fillStyle = 'rgb(246,246,244)'; g.fillText(W_.w, x, y); g.shadowBlur = 0;
      // container: the picture area of the frame (inside the gate, clear of the phone's UI on 9:16), with margin
      CPROBE.text(g, 'lyric', W_.w, x, y, { inScreen: [area[0], area[1], area[2] - area[0], area[3] - area[1]], margin: 6 });
    }
  }
  g.restore();
}

// ---------- the frame ----------
// faces: reported as probe records so the audit spec can check every lyric block against every head
function capReportFaces(map) {
  for (const b of FACES) { const r = map ? map(b) : b; if (r) capRec({ kind: 'box', name: 'face', box: r, frame: CAP_TALL ? [TW, TH] : [W, H] }); }
}
// the pan-and-scan window centre (16:9 design px) at t, as vertical.mjs in bobwiseman-me-and-jimi
function capCx(t) {
  if (window.__capCx !== undefined) return window.__capCx;
  const K = PANPLAN.keys, ss = (u) => u * u * (3 - 2 * u);
  if (t <= K[0][0]) return K[0][1];
  for (let i = 0; i + 1 < K.length; i++) { const [a, ca] = K[i], [b, cb] = K[i + 1]; if (t >= a && t < b) return b - a < .05 ? ca : ca + (cb - ca) * ss((t - a) / (b - a)); }
  return K[K.length - 1][1];
}
const capX0 = (t) => clamp(capCx(t) - CROPW / 2, 0, W - CROPW);
const capToTall = (x0) => (b) => [(b[0] - x0) * TW / CROPW, b[1] * TH / 1080, (b[2] - x0) * TW / CROPW, b[3] * TH / 1080];
const TALLC = mkCanvas(TW, TH), capTg = TALLC.getContext('2d');
let CAP_SUPPRESS = false;     // set while the tall page draws the 16:9 frame (the caption goes on the tall frame)
function capFrameDraw(t) {
  FACES = [];
  CAP_SUPPRESS = CAP_TALL;
  renderFrame(t);
  CAP_SUPPRESS = false;
  if (window.CAP_AFTER && !CAP_TALL) window.CAP_AFTER(t);
  if (!CAP_TALL) { capReportFaces(); return out; }
  const x0 = capX0(t);
  capTg.setTransform(1, 0, 0, 1, 0, 0); capTg.imageSmoothingEnabled = true; capTg.imageSmoothingQuality = 'high';
  capTg.drawImage(out, x0, 0, CROPW, 1080, 0, 0, TW, TH);
  capDraw(capTg, t, "tall");
  capReportFaces(capToTall(x0));
  return TALLC;
}
window.__frameJPEG = (t, q = .93) => capFrameDraw(t).toDataURL('image/jpeg', q);
// for tools/place_captions.mjs: draw frame t and report the faces (in the aspect's px), the shot and the layout sizes
window.__capScan = (t) => {
  FACES = []; CAP_SUPPRESS = true; renderFrame(t); CAP_SUPPRESS = false;
  const key = capKey(), li = capLine(t), x0 = CAP_TALL ? capX0(t) : 0, m = CAP_TALL ? capToTall(x0) : (b) => b;
  return { faces: FACES.map(m), shot: String(window.capShot ? window.capShot(t) : ''), li, w0: li < 0 ? 0 : Math.floor(LYR[li].words[0].s * CAP_F + 1e-6),
    lays: li < 0 ? [] : CAP_STYLE[CAP_KIND][key].layouts.map((_, n) => { const L = capLay(li, key, n); return [L.w, L.h]; }),
    area: CAP_STYLE[CAP_KIND][key].area, bottom: CAP_STYLE[CAP_KIND][key].bottom, kind: CAP_KIND, W: CAP_TALL ? TW : W, H: CAP_TALL ? TH : H };
};
