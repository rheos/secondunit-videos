// aspects/9x16/panscan-plan-v1.json (tools/panscan_plan.mjs) + the hand edits in aspects/9x16/panscan-edits-v1.json
// -> aspects/9x16/panscan-plan-v1.js (const PANPLAN), so the 9:16 caption pages read the plan without file:// fetches.
// An edit is {f0, f1, cx[, cx1], why}: song frames [f0, f1) hold the window at cx (or pan cx -> cx1), replacing the
// proposal there. Numbers only. Run after every change to either file: node tools/plan_js.mjs
import fs from 'fs';
const p = JSON.parse(fs.readFileSync('aspects/9x16/panscan-plan-v1.json', 'utf8'));
const E = fs.existsSync('aspects/9x16/panscan-edits-v1.json') ? JSON.parse(fs.readFileSync('aspects/9x16/panscan-edits-v1.json', 'utf8')).edits : [];
let K = p.keys.slice();
for (const e of E) {
  const a = e.f0 / 24, b = e.f1 / 24;
  K = K.filter((k) => k[0] < a - 1e-6 || k[0] >= b - 1e-6).concat([[a, e.cx], [b - .01, e.cx1 ?? e.cx]]);
}
K.sort((x, y) => x[0] - y[0]);
fs.writeFileSync('aspects/9x16/panscan-plan-v1.js', '// GENERATED by tools/plan_js.mjs from panscan-plan-v1.json + panscan-edits-v1.json. Do not edit.\nconst PANPLAN = ' + JSON.stringify({ ...p, keys: K }) + ';\n');
console.log('wrote aspects/9x16/panscan-plan-v1.js', K.length, 'keys,', E.length, 'edits');
