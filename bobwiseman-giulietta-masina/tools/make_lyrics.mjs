// Writes js/gen/lyrics.js (const LYR) from source/lines.json (tools/build_lines.py). Run from the project folder:
// node tools/make_lyrics.mjs. The output quotes the lyric, so js/gen/ is gitignored. Never edit it by hand.
import fs from 'fs';
const d = JSON.parse(fs.readFileSync('source/lines.json', 'utf8'));
const lines = d.lines.map((l) => ({ a: l.a, b: l.b, it: l.it, words: l.words.map((w) => ({ w: w.w, s: w.s })) }));
fs.mkdirSync('js/gen', { recursive: true });
fs.writeFileSync('js/gen/lyrics.js', `// GENERATED by tools/make_lyrics.mjs from source/lines.json (${d.sha256.slice(0, 12)}). Do not edit.\nconst LYR = ${JSON.stringify(lines)};\n`);
console.log('wrote js/gen/lyrics.js:', lines.length, 'lines,', lines.reduce((a, l) => a + l.words.length, 0), 'words');
