// sync.mjs: write shared/spec.json into the HyperFrames page as a plain script (hyperframes/spec.js).
// The Remotion build imports the JSON directly; a static HTML page cannot, and a fetch at render time
// is banned by the HyperFrames determinism rules. Run after any change to spec.json:
//   node shared/sync.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const spec = fs.readFileSync(path.join(here, 'spec.json'), 'utf8');
const out = path.join(here, '..', 'hyperframes', 'spec.js');
fs.writeFileSync(out, `// generated by shared/sync.mjs from shared/spec.json; edit the JSON, not this file\nwindow.ONESHOW_SPEC = ${spec.trim()};\n`);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
