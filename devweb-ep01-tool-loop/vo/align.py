#!/usr/bin/env python3
"""Word times for the take (faster-whisper small.en, timing only; the words come from vo.py), placed at LEAD seconds
into the film. Writes vo/words.json and vo/words.js (window.VO): VO.w("harness") = film time George starts "harness"
(first match; VO.w(word, 2) the second), VO.e(...) its end. Also writes _in/voice.wav at the film's length."""
import json, pathlib, subprocess
from faster_whisper import WhisperModel
HERE = pathlib.Path(__file__).parent; ROOT = HERE.parent
LEAD, TAIL = 0.6, 4.4
take = json.loads((HERE / "take.json").read_text())
END = round(LEAD + take["seconds"] + TAIL, 3)
m = WhisperModel("small.en", device="cpu", compute_type="int8")
res, _ = m.transcribe(str(HERE / "voice.mp3"), word_timestamps=True, beam_size=5)
W = [[w.word.strip().strip(".,:;!?").lower(), round(LEAD + w.start, 3), round(LEAD + w.end, 3)] for r in res for w in r.words]
(HERE / "words.json").write_text(json.dumps({"lead": LEAD, "end": END, "words": W}, indent=1) + "\n")
(HERE / "words.js").write_text(
  "// generated by vo/align.py (faster-whisper word times; timing only, the words are vo.py's)\n"
  f"window.VO = {{ END: {END}, W: {json.dumps(W)},\n"
  "  w(word, n = 1) { const m = this.W.filter((x) => x[0] === word.toLowerCase()); if (m.length < n) throw new Error(`VO: no '${word}' #${n}`); return m[n - 1][1]; },\n"
  "  e(word, n = 1) { const m = this.W.filter((x) => x[0] === word.toLowerCase()); if (m.length < n) throw new Error(`VO: no '${word}' #${n}`); return m[n - 1][2]; } };\n")
ms = round(LEAD * 1000)
subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(HERE / "voice.mp3"), "-af",
  f"aresample=48000,aformat=channel_layouts=stereo,adelay={ms}|{ms},apad=whole_dur={END},atrim=0:{END}",
  "-c:a", "pcm_s16le", str(ROOT / "_in/voice.wav")], check=True)
print("END", END); print(" ".join(f"{w}@{a}" for w, a, b in W))
