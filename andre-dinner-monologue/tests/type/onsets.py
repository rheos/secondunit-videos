"""Snap the type look's hit words to onsets of _in/andre.wav and write js/words.js.

    $PY onsets.py            (run from tests/type/)

Onset strength = rise in log energy over 40 ms (10 ms hops, 40 ms RMS window). For each word in the
section, the candidate peaks within +-0.6 s of the Whisper cue are scored by strength times a
Gaussian of their distance (sigma 0.2 s): in this section Whisper runs only 0.05 to 0.2 s off,
so the window is -0.15 to +0.45 s around the cue. A peak under the weak threshold keeps the cue
time; a peak two neighbours both want goes to the word whose cue is nearer, the other keeps its cue. Checked by hand against the peak dump for every hit word (NOTES.md). Output: js/words.js, a global WORDS
array of [word, snappedFrame, cueFrame, snappedSeconds] for f504..f1188, plus the segment frame list.
"""
import json, sys, wave
import numpy as np

FPS = 24
F0, F1 = 504, 1188
WAV = '../../_in/andre.wav'
CUES = '../../_in/cues.json'
HOP, WIN = 0.010, 0.040
WEAK = 1.5  # log-energy rise (natural log) below which the cue time is kept

with wave.open(WAV) as w:
    sr, n, ch = w.getframerate(), w.getnframes(), w.getnchannels()
    pcm = np.frombuffer(w.readframes(n), np.int16).reshape(-1, ch).astype(np.float32) / 32768
mono = pcm.mean(axis=1)
hop, win = int(sr * HOP), int(sr * WIN)
nh = (len(mono) - win) // hop
sq = np.concatenate([[0], np.cumsum(mono * mono)])
energy = (sq[np.arange(nh) * hop + win] - sq[np.arange(nh) * hop]) / win
logE = np.log(energy + 1e-7)
lag = int(round(WIN / HOP))
rise = np.zeros_like(logE)
rise[lag:] = logE[lag:] - logE[:-lag]
rise = np.maximum(rise, 0)
times = np.arange(nh) * HOP + WIN / 2  # the rise is attributed to the end of the window

def peaks(lo, hi):
    i0, i1 = max(1, int(lo / HOP)), min(nh - 1, int(hi / HOP))
    out = []
    for i in range(i0, i1):
        if rise[i] >= rise[i - 1] and rise[i] > rise[i + 1] and rise[i] > 0:
            out.append((times[i], float(rise[i])))
    return out

cues = json.load(open(CUES))
words = [w for w in cues['words'] if F0 <= w['f0'] < F1]
# pass 1: every word's best peak; pass 2: a peak claimed by two neighbours goes to the nearer cue
picks = []
for w in words:
    t0 = w['t0']
    best, best_s, raw = None, -1, 0
    for pt, st in peaks(t0 - 0.15, t0 + 0.45):
        sc = st * np.exp(-((pt - t0) / 0.2) ** 2)
        if sc > best_s:
            best, best_s, raw = pt, sc, st
    picks.append(None if best is None or raw < WEAK else (best, raw))
for i in range(1, len(words)):
    a, b = picks[i - 1], picks[i]
    if a and b and abs(a[0] - b[0]) < 0.005:
        if abs(a[0] - words[i - 1]['t0']) <= abs(b[0] - words[i]['t0']):
            picks[i] = None
        else:
            picks[i - 1] = None
rows = []
for w, p in zip(words, picks):
    t0 = w['t0']
    snapped, how = (t0, 'cue') if p is None else (p[0], f'onset {p[1]:.2f}')
    rows.append([w['w'], int(round(snapped * FPS)), w['f0'], round(float(snapped), 3), how])
    print(f"{w['w']:16s} cue f{w['f0']:4d} {t0:6.2f}  ->  f{rows[-1][1]:4d} {snapped:6.2f}  ({how})")

# keep the order monotonic: a snapped frame never precedes the previous word's snapped frame
for i in range(1, len(rows)):
    if rows[i][1] < rows[i - 1][1]:
        rows[i][1] = rows[i - 1][1]
# voice level per 24 fps frame for the readout strip's meter: RMS over the frame, normalised to the 95th percentile
rms = np.array([np.sqrt(np.mean(mono[int(f * sr / FPS):int((f + 1) * sr / FPS)] ** 2)) for f in range(F0, F1)])
voc = np.clip(rms / np.percentile(rms, 95), 0, 1)
with open('js/words.js', 'w') as f:
    f.write('// generated by onsets.py from _in/cues.json + onsets of _in/andre.wav; [word, frame, cueFrame, seconds, how]\n')
    f.write('const WORDS = ' + json.dumps([r for r in rows]) + ';\n')
    f.write(f'const VOC0 = {F0}; const VOC = [' + ','.join(f'{v:.2f}' for v in voc) + '];\n')
print('wrote js/words.js', len(rows), 'words')
