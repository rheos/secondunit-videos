"""Snap key words of the table-city section to onsets of _in/andre.wav and write js/cues.js.

Method (docs/BRIEF.md): rise in log energy over 40 ms; strongest rise within +-0.25 s of the Whisper cue
time, then +-0.6 s; keep the cue time when the rise is weak (under 6 dB). Run from tests/table-city/:
    $PY tools/onsets.py
"""
import json, os, sys, wave
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
FPS = 24
KEYS = [  # (key, word text, Whisper frame f0 from cues.json, segment id)
    ('findhorn1', 'Findhorn,', 1819, 7), ('trees', 'trees.', 1934, 7), ('back', 'back', 1956, 7),
    ('redwoods', 'redwoods.', 2000, 7), ('eighty4', '84', 2020, 7), ('backpack', 'backpack,', 2070, 7),
    ('tomorrow', 'tomorrow.', 2108, 7), ('from', 'from?', 2198, 8), ('newyork1', 'New', 2215, 8),
    ('york1', 'York.', 2218, 8), ('newyork2', 'New', 2235, 8), ('york2', 'York,', 2238, 8),
    ('leave1', 'leave', 2342, 8), ('never', 'never', 2350, 8), ('yes', 'yes.', 2379, 9),
    ('why', 'why', 2404, 9), ('leave2', 'leave?', 2424, 9), ('gave', 'gave', 2442, 9),
    ('theories', 'theories.', 2462, 9), ('oh', 'oh,', 2491, 9), ('all', 'all.', 2520, 9),
]

with wave.open(os.path.join(PROJ, '_in', 'andre.wav'), 'rb') as w:
    sr, n, ch = w.getframerate(), w.getnframes(), w.getnchannels()
    pcm = np.frombuffer(w.readframes(n), np.int16).reshape(-1, ch).mean(axis=1) / 32768.0
hop, win = int(sr * 0.005), int(sr * 0.040)
nf = (len(pcm) - win) // hop
e = np.array([np.log10(np.mean(pcm[i * hop:i * hop + win] ** 2) + 1e-9) * 10 for i in range(nf)])
rise = np.zeros_like(e); rise[8:] = e[8:] - e[:-8]      # rise over 40 ms (8 hops of 5 ms)

cues = json.load(open(os.path.join(PROJ, '_in', 'cues.json')))
out, report = {}, []
for key, text, f0, seg in KEYS:
    w = next((x for x in cues['words'] if x['seg'] == seg and x['f0'] == f0 and x['w'] == text), None)
    assert w, (key, text, f0)
    # the strongest rise near the cue first (+-0.25 s), then the brief's +-0.6 s; a neighbouring word's
    # rise 0.5 s away is louder than the word itself for "New York" and "all", so near wins
    t = w['t0']; snapped, r = w['f0'], 0.0
    for half in (0.25, 0.6):
        a, b = int((t - half) / 0.005), int((t + half) / 0.005)
        k = a + int(np.argmax(rise[a:b])); r = rise[k]
        if r >= 6: snapped = round((k * 0.005 + 0.020) * FPS); break   # the rise window's centre
    out[key] = {'w': text, 'cue': w['f0'], 'f': int(snapped), 'rise_db': round(float(r), 1), 't': round(snapped / FPS, 3)}
    report.append(f"{key:10s} {text:12s} cue f{w['f0']}  onset f{snapped} ({snapped - w['f0']:+d})  rise {r:.1f} dB")
print('\n'.join(report))
with open(os.path.join(HERE, '..', 'js', 'cues.js'), 'w') as f:
    f.write('// generated by tools/onsets.py from _in/cues.json and onsets of _in/andre.wav; frames at 24 fps\n')
    f.write('const CUES = ' + json.dumps(out, indent=1) + ';\n')
