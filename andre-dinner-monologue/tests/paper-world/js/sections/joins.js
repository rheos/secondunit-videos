// joins.js: the camera at every boundary between two sections, so the film is one move. A section's first camera key is
// joinKey(F0) and its last is joinKey(F1): position P, target T and their velocity per frame (mP, mT), which the spline
// takes as its tangent there. Where a neighbour is built the join is read from it: f1800 is section 5's first key with
// its velocity, f3397 is where section 7's spline is at that frame. f4761 is the end of the film: not a join.
// `float` is the size of the camera's slow circle at the join, as a share of section 5's (camFrom's third argument):
// pass joinFloat(F0, F1, f) and the float carries across too.
// Builders do not edit this file: if a join is in the wrong place for a section, keep to it and say so.
import { setJoin, joinKey, joinFloat, handover } from "./lib.js";
import * as S5 from "./s05.js";
import * as S7 from "./s07.js";

//          f     P                T                  mP                     mT
const J = [[0, [-2, 16, 96], [8, 9, -10], [0.01, -0.03, -0.12], [0, 0, 0]],
  [196, [-5, 9, 70], [1, 3.5, 44], [0.01, -0.005, -0.05], [0.004, 0, -0.01]],
  [504, [-8, 11, 60], [-3, 4, 30], [-0.03, 0.03, -0.12], [-0.05, 0, -0.3]],
  [1196, [-17, 5, -39], [-30, 2.2, -50], [0.02, 0.01, 0.04], [0.02, 0, 0.05]],
  [3840, [-58, 18, 16], [-170, 10, 4], [-0.04, 0.01, 0], [0, 0, 0]],
  [4315, [-12, 4, 36], [2, 3, 10], [-0.01, 0.01, 0.05], [0, 0, 0]]];
for (const [f, P, T, mP, mT] of J) setJoin(f, { P, T, mP, mT, float: 0.5 });
setJoin(S5.F0, { ...handover(S5.CAM_KEYS, S5.F0), float: 1 });           // f1800: section 5's first key, with its velocity
setJoin(S7.F1, { ...handover(S7.CAM_KEYS, S7.F1), float: 0.5 });         // f3397: section 7's spline a frame past its last
export const JOIN_FRAMES = [...J.map((j) => j[0]), S5.F0, S7.F1].sort((a, b) => a - b);
export { joinKey, joinFloat };
