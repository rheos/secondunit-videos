# align-mms.json -> js/cut/words.js (gitignored: it quotes the lyric)
# WORDS: [{w, s, e, line}] in sung order; LINES: [{text, s, e}]; wordAt('reunion', n) finds the nth match.
import json, sys
d = json.load(open(sys.argv[1]))
words = [{"w": w["w"], "s": w["s"], "e": w["e"], "line": w["line"]} for w in d["words"]]
lines = []
for li, text in enumerate(d["lines"]):
    ws = [w for w in words if w["line"] == li]
    lines.append({"text": text, "s": ws[0]["s"], "e": ws[-1]["e"]})
js = "// Generated by work/mkwords.py from the MMS alignment of the vocal stem. Song seconds.\n"
js += "const WORDS = " + json.dumps(words, ensure_ascii=False) + ";\n"
js += "const LINES = " + json.dumps(lines, indent=0, ensure_ascii=False) + ";\n"
js += """// wordAt('reunion', 2) -> start time of the 3rd sung 'reunion' (case and punctuation ignored)
function wordAt(word, n = 0, from = 0) {
  const norm = (x) => x.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z]/g, '');
  const hits = WORDS.filter((w) => norm(w.w) === norm(word) && w.s >= from);
  return hits.length ? hits[Math.min(n, hits.length - 1)].s : NaN;
}
"""
open(sys.argv[2], "w", encoding="utf-8").write(js)
print(len(words), "words,", len(lines), "lines")
