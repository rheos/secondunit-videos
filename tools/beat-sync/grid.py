"""The song's 16th-note grid for beat-sync.html, and the way back from the cells Robin paints to times.

  grid.py grid <song.wav> <out.js> --downbeat 37.616 [--bpm 100]
      beat-tracks the song, splits each beat into four 16ths and writes
      `const BEAT_GRID = [...], BEAT_REF = <index>;` (BEAT_REF is the grid index of a known downbeat, so the page can
      draw the bar lines; pick any first-beat-of-the-bar you can hear, e.g. where the part starts).
  grid.py times <grid.js> <cells.json> [--snap <stem.wav> ...] > times.json
      turns the page's cells (grid indices, from "Copy cells" or window.BEATSYNC_CELLS) into times; with --snap, each
      time moves to the strongest onset within 20 ms in the given stems (half a frame at 24 fps, so the rhythm stays even).

Run with a Python that has librosa (on this Mac: ~/Code/novadiem/indieagent/viralvision/viralvision-worker/.venv/bin/python -I).
"""
import sys, json, re
import numpy as np


def beat_grid(song, bpm):
    import librosa
    y, sr = librosa.load(song, sr=22050, mono=True)
    _, beats = librosa.beat.beat_track(y=y, sr=sr, hop_length=256, units='time', start_bpm=bpm, tightness=400)
    return np.array([b + (beats[i + 1] - b) * q / 4 for i, b in enumerate(beats[:-1]) for q in range(4)])


def onset_env(path, sr=22050, hop=64):
    import librosa
    y, _ = librosa.load(path, sr=sr, mono=True)
    S = np.abs(librosa.stft(y, n_fft=1024, hop_length=hop)); f = librosa.fft_frequencies(sr=sr, n_fft=1024)
    L = np.log1p(S[(f > 150) & (f < 2500)] * 10); e = np.maximum(0, np.diff(L, axis=1)).mean(0)
    e = np.convolve(e, np.ones(3) / 3, 'same'); return e / np.median(e), sr / hop


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


if __name__ == '__main__':
    mode = sys.argv[1]
    if mode == 'grid':
        song, out = sys.argv[2], sys.argv[3]
        g = beat_grid(song, float(arg('--bpm', 100)))
        ref = int(np.argmin(abs(g - float(arg('--downbeat', g[0])))))
        open(out, 'w').write('// Generated by tools/beat-sync/grid.py: the song\'s 16th-note grid (s) and a downbeat index.\n'
                             f'const BEAT_GRID = {json.dumps([round(float(x), 3) for x in g])}, BEAT_REF = {ref};\n')
        print(f'{len(g)} sixteenths, median step {np.median(np.diff(g)):.3f} s, downbeat index {ref} at {g[ref]:.3f} s')
    elif mode == 'times':
        src = open(sys.argv[2]).read()
        grid = json.loads(re.search(r'=\s*(\[[^\]]*\])', src).group(1))
        cells = json.load(open(sys.argv[3])); times = [grid[k] for k in cells]
        stems = sys.argv[sys.argv.index('--snap') + 1:] if '--snap' in sys.argv else []
        if stems:
            envs = [onset_env(p) for p in stems]; fr = envs[0][1]; n = min(len(e) for e, _ in envs)
            env = np.max([e[:n] for e, _ in envs], axis=0)
            def snap(t):
                i0, i1 = int((t - .02) * fr), int((t + .02) * fr) + 1; j = i0 + int(np.argmax(env[i0:i1]))
                return j / fr if env[j] >= 1.6 else t
            times = [snap(t) for t in times]
        print(json.dumps([round(t, 3) for t in times]))
