"""Build toolbox/INDEX.md from toolbox/*.yaml, or check it is current.

    uv run --no-project --with pyyaml python toolbox/index.py          # write INDEX.md
    uv run --no-project --with pyyaml python toolbox/index.py --check  # fail if stale or a file is invalid
"""
import sys
from collections import defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).parent
STATUSES = ["in-use", "available", "candidate", "rejected", "retired"]
REQUIRED = ["slug", "name", "kind", "status", "does", "keywords", "how", "cost"]


def load():
    tools, errors = [], []
    for path in sorted(HERE.glob("*.yaml")):
        t = yaml.safe_load(path.read_text())
        missing = [f for f in REQUIRED if not t.get(f)]
        if missing:
            errors.append(f"{path.name}: missing {', '.join(missing)}")
        if t.get("slug") != path.stem:
            errors.append(f"{path.name}: slug is {t.get('slug')!r}, must match the file name")
        if t.get("status") not in STATUSES:
            errors.append(f"{path.name}: status {t.get('status')!r} is not one of {', '.join(STATUSES)}")
        if t.get("status") == "rejected" and not t.get("why"):
            errors.append(f"{path.name}: a rejected tool needs a why")
        tools.append(t)
    slugs = {t.get("slug") for t in tools}
    for t in tools:
        for r in t.get("related", []):
            if r not in slugs:
                errors.append(f"{t['slug']}.yaml: related {r!r} has no file")
    return tools, errors


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(tools):
    out = ["# Toolbox index", "",
           "Generated by `toolbox/index.py` from the YAML files. Don't edit by hand; see README.md.", ""]
    for status in STATUSES:
        group = sorted((t for t in tools if t["status"] == status), key=lambda t: t["name"].lower())
        if not group:
            continue
        out += [f"## {status} ({len(group)})", "", "| Tool | Does | Keywords |", "|---|---|---|"]
        for t in group:
            extra = f" Why not: {t['why']}" if status == "rejected" else ""
            out.append(f"| [{cell(t['name'])}]({t['slug']}.yaml) | {cell(t['does'])}{cell(extra)} | {cell(', '.join(t['keywords']))} |")
        out.append("")
    by_kw = defaultdict(list)
    for t in tools:
        for k in t["keywords"]:
            by_kw[k].append(t["slug"])
    out += ["## By keyword", ""]
    out += [f"- **{k}**: {', '.join(sorted(v))}" for k, v in sorted(by_kw.items())]
    return "\n".join(out) + "\n"


def main():
    tools, errors = load()
    if errors:
        sys.exit("toolbox: " + "\n toolbox: ".join(errors))
    text, index = render(tools), HERE / "INDEX.md"
    if "--check" in sys.argv:
        if not index.exists() or index.read_text() != text:
            sys.exit("toolbox: INDEX.md is stale; run toolbox/index.py and commit it")
        print(f"toolbox: {len(tools)} tools, INDEX.md current")
    else:
        index.write_text(text)
        print(f"toolbox: wrote INDEX.md for {len(tools)} tools")


if __name__ == "__main__":
    main()
