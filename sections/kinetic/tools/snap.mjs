// node tools/snap.mjs  ->  js/lyrics.js (gitignored)
// The improv has no lyric sheet, so the words come from Whisper medium. Only fragments that held up in a
// second pass (small.en + medium on the vocal stem, 2026-10-03) are kept as text; the rest become
// [UNINTELLIGIBLE] spans or vocal-hit markers. Word times are snapped to the real vocal onsets:
// onset candidates are FEAT.vonsets plus rising edges of the voc envelope (vonsets miss some syllables);
// each word takes the nearest candidate in [-0.1, +0.3] s of its Whisper start (Whisper runs early),
// keeping words in order at least 0.06 s apart.
import fs from 'fs';
const SRC = '/Users/robin/Code/novadiem/indieagent/secondunit/mv-projects/bobwiseman-airplane-on-the-highway/source/words-whisper-medium.json';
const L = JSON.parse(fs.readFileSync(SRC, 'utf8')).lines;
globalThis.window = {}; await import('../js/data.js'); const FT = window.FEAT, V = FT.voc;
const EDGE = []; for (let i = 2; i < V.length - 2; i++) { const d = V[i] - V[i - 2], dp = V[i - 1] - V[i - 3], dn = V[i + 1] - V[i - 1]; if (d > .035 && d >= dp && d >= dn) EDGE.push((i - 1) / FT.fps); }
const VON = [...FT.vonsets, ...EDGE].sort((a, b) => a - b);
const near = (t, lo, hi) => { let best = null; for (const v of VON) if (v >= t + lo && v <= t + hi && (best === null || Math.abs(v - t) < Math.abs(best - t))) best = v; return best; };
// [key, line index, first word, last word (inclusive)]
const KEEP = {
  A: [['sky', 0], ['sky2', 1], ['ground', 2], ['onground', 3], ['airplane', 4], ['notright', 5], ['rooms', 8], ['belts', 9], ['getin', 10, 0, 5]],
  K: [['sky', 43, 0, 10], ['sky2', 43, 11, 18], ['ground', [[43, 19, 21], [44, 0, 4]]], ['onground', 44, 5, 7], ['airplane', 44, 8, 10], ['notright', 44, 11, 13],
    ['queen', 45], ['apologies', 46, 0, 0], ['wings', 46, 1, 9]],
};
const UNK = { A: [6, 7, 14, 15], K: [] };
const HITS = { A: [11, 12, 13, 16, 17, 18, 19, 20, 21], K: [] };
// corrections from people who listened (tools/fixes.json, gitignored): word text by index, same timings
const FIX = fs.existsSync(new URL('./fixes.json', import.meta.url)) ? JSON.parse(fs.readFileSync(new URL('./fixes.json', import.meta.url), 'utf8')) : {};
const r3 = (x) => Math.round(x * 1000) / 1000;
const out = {};
for (const sec of ['A', 'K']) {
  const lines = {};
  for (const [key, li, a = 0, b] of KEEP[sec]) {
    const ws = Array.isArray(li) ? li.flatMap(([l, x, y]) => L[l].words.slice(x, y + 1)) : L[li].words.slice(a, b === undefined ? undefined : b + 1);
    let prev = -1;
    const words = ws.map((w) => { let v = near(w.s, -.1, .3); if (v === null || v < prev + .06) v = Math.max(w.s, prev + .06); prev = v; return [w.t.replace(/[.,]$/, ''), r3(v)]; });
    const e = r3(Math.max(ws[ws.length - 1].e, prev + .2));
    const fx = FIX[sec]?.[key]; if (fx) { for (const [i, w] of Object.entries(fx.words)) words[i][0] = w; for (const [i, v] of Object.entries(fx.times || {})) words[i][1] = v; }
    lines[fx?.key || key] = { text: words.map((w) => w[0]).join(' '), words, e, ...(fx?.unclear ? { unclear: fx.unclear } : {}) };
  }
  out[sec] = {
    lines,
    unk: UNK[sec].map((i) => { const s0 = near(L[i].s, -.15, .4) ?? L[i].s; return [r3(s0), r3(L[i].e)]; }),
    hits: HITS[sec].map((i) => { const s0 = near(L[i].s, -.2, .4) ?? L[i].s; return [r3(s0), /^N/.test(L[i].text) ? '[YELP]' : '[WHOOP]']; }),
  };
}
fs.writeFileSync(new URL('../js/lyrics.js', import.meta.url), `// GENERATED by tools/snap.mjs. Bob Wiseman, "Airplane on the Highway" (2026): Whisper fragments of the improv.\n// Kept out of git. Times are seconds on the song clock, snapped to FEAT.vonsets.\nwindow.LYR = ${JSON.stringify(out, null, 1)};\n`);
for (const sec of ['A', 'K']) for (const [k, v] of Object.entries(out[sec].lines)) console.log(sec, k.padEnd(10), v.words.map(([w, t]) => `${w}@${t}`).join(' '));
console.log(JSON.stringify(out.A.unk), JSON.stringify(out.A.hits));
