#!/usr/bin/env python3
"""Place the narration: each plate's segment at T + VO (timeline.json) -> _in/voice.wav (48 kHz stereo, the film's
length), and the word times as absolute film seconds -> vo/words.js (window.VO), so plates cue on words:
VO.w("IV", "scrubs") is the film time George starts "scrubs" (first match; VO.w(plate, word, 2) the second)."""
import json, pathlib, subprocess
HERE = pathlib.Path(__file__).parent; ROOT = HERE.parent
tl = json.loads((HERE / "timeline.json").read_text()); segs = json.loads((HERE / "segments.json").read_text())
words = json.loads((HERE / "words.json").read_text())
args = ["ffmpeg", "-y", "-v", "error"]; chain = []
for i, s in enumerate(segs):
    args += ["-i", str(HERE / s["file"])]
    ms = round((tl["T"][s["plate"]] + tl["VO"][s["plate"]]) * 1000)
    chain.append(f"[{i}:a]aresample=48000,aformat=channel_layouts=stereo,adelay={ms}|{ms}[v{i}]")
chain.append("".join(f"[v{i}]" for i in range(len(segs))) + f"amix=inputs={len(segs)}:normalize=0,apad=whole_dur={tl['END']},atrim=0:{tl['END']}[out]")
(ROOT / "_in").mkdir(exist_ok=True)
subprocess.run(args + ["-filter_complex", ";".join(chain), "-map", "[out]", "-c:a", "pcm_s16le", str(ROOT / "_in/voice.wav")], check=True)
W = {k: [[w.strip(".,:;!?").lower(), round(tl["T"][k] + tl["VO"][k] + a, 3), round(tl["T"][k] + tl["VO"][k] + b, 3)] for w, a, b in ws] for k, ws in words.items()}
js = ("// generated by vo/place.py from vo/timeline.json and vo/words.json (faster-whisper word times; timing only)\n"
      f"window.VO = {{ T: {json.dumps(tl['T'])}, END: {tl['END']}, W: {json.dumps(W)},\n"
      "  w(p, word, n = 1) { const m = this.W[p].filter((x) => x[0] === word.toLowerCase()); if (m.length < n) throw new Error(`VO: no '${word}' #${n} in ${p}`); return m[n - 1][1]; },\n"
      "  e(p, word, n = 1) { const m = this.W[p].filter((x) => x[0] === word.toLowerCase()); if (m.length < n) throw new Error(`VO: no '${word}' #${n} in ${p}`); return m[n - 1][2]; } };\n")
(HERE / "words.js").write_text(js)
print("voice.wav", tl["END"], "s; words.js", sum(len(v) for v in W.values()), "words")
